def build_question(en_q, ar_qmap):
    qid = en_q["id"]
    ar = ar_qmap.get(qid)
    if not ar:
        raise SystemExit(f"Missing Arabic for {qid}")
    options = []
    en_opts = {o["key"]: o["text"] for o in en_q["options"]}
    for o in en_q["options"]:
        key = o["key"]
        if key not in ar["options"]:
            raise SystemExit(f"Missing option {key} for {qid}")
        options.append({"key": key, "text": ar["options"][key]})
    if len(options) != len(en_q["options"]):
        raise SystemExit(f"Option count mismatch {qid}")
    return {
        "id": qid,
        "question_text": ar["question_text"],
        "options": options,
        "correct": en_q["correct"],  # identity from English
        "explanation": ar.get("explanation", en_q.get("explanation", "")),
    }


def main():
    with open(EN_PATH, encoding="utf-8") as f:
        en_data = json.load(f)
    with open(AR_PATH, encoding="utf-8") as f:
        ar_data = json.load(f)

    en_by_ch = {e["chapter_id"]: e for e in en_data["exams"]}
    ar_by_ch = {e["chapter_id"]: e for e in ar_data["exams"]}

    updated = 0
    total_q = 0
    for cid, ar_meta in AR.items():
        if cid not in en_by_ch:
            raise SystemExit(f"English missing chapter {cid}")
        en_exam = en_by_ch[cid]
        ar_questions = []
        for en_q in en_exam["questions"]:
            ar_questions.append(build_question(en_q, ar_meta["questions"]))
            total_q += 1
        if len(ar_questions) != len(en_exam["questions"]):
            raise SystemExit(f"Question count mismatch {cid}")

        new_exam = {
            "chapter_id": cid,
            "title": ar_meta["title"],
            "description": ar_meta["description"],
            "instructions": ar_meta["instructions"],
            "questions": ar_questions,
        }
        ar_by_ch[cid] = new_exam
        updated += 1
        print(f"OK {cid}: {len(ar_questions)} questions — {ar_meta['title']}")

    # Preserve exam order from English file
    new_exams = []
    for e in en_data["exams"]:
        cid = e["chapter_id"]
        if cid in ar_by_ch:
            new_exams.append(ar_by_ch[cid])
        else:
            new_exams.append(e)

    ar_data["exams"] = new_exams
    with open(AR_PATH, "w", encoding="utf-8") as f:
        json.dump(ar_data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"\nUpdated {updated} exams, {total_q} questions written to {AR_PATH}")

    # Verify no English-only remaining for pyf/pyl2
    with open(AR_PATH, encoding="utf-8") as f:
        check = json.load(f)
    issues = []
    for e in check["exams"]:
        if not e["chapter_id"].startswith(("chap-pyf-", "chap-pyl2-")):
            continue
        if not any("\u0600" <= c <= "\u06FF" for c in e["title"]):
            issues.append(f"title {e['chapter_id']}")
        for q in e["questions"]:
            if not any("\u0600" <= c <= "\u06FF" for c in q["question_text"]):
                # allow pure code questions
                if len(q["question_text"]) > 8:
                    issues.append(f"qtext {q['id']}")
            for o in q["options"]:
                t = o["text"]
                if len(t) > 20 and not any("\u0600" <= c <= "\u06FF" for c in t):
                    # allow pure code/identifiers
                    if not any(ch.isalpha() and ord(ch) < 128 for ch in t):
                        pass
                    elif t.replace(" ", "").isalnum() or any(x in t for x in ("()", "[", "]", "**", "==", "+=", "f\"")):
                        pass
                    else:
                        issues.append(f"opt {q['id']} {o['key']}: {t[:40]}")
    print("Remaining issues:", issues if issues else "none")


if __name__ == "__main__":
    main()
